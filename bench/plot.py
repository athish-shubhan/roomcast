#!/usr/bin/env python3
"""results/*.jsonl -> figures + results/SUMMARY.md for RoomCast."""
import json
import math
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

d = sys.argv[1]
CLASSES = ["moderation", "auction", "battle", "gift", "comment"]
SLO = {"moderation": 1000, "auction": 200, "battle": 200, "gift": 500, "comment": 1000}
COL = {"std": "#9aa5b1", "epoll": "#2bb3a3", "netpoll": "#c75b7a"}


def hq(h, q):
    if not h or h["n"] == 0:
        return float("nan")
    t, c = math.ceil(q * h["n"]), 0
    for i, n in enumerate(h["b"]):
        c += n
        if c >= t:
            return 10 ** ((i + 1) / 20 - 2)
    return float("inf")


def within(h, ms):
    if not h or h["n"] == 0:
        return float("nan")
    c = 0
    for i, n in enumerate(h["b"]):
        if 10 ** ((i + 1) / 20 - 2) > ms * 1.0001:
            break
        c += n
    return c / h["n"]


def merge(hs):
    out = {"b": [0] * 161, "n": 0}
    for h in hs:
        if not h:
            continue
        out["n"] += h["n"]
        for i, n in enumerate(h["b"]):
            out["b"][i] += n
    return out


def window(r, fin, cls, burst):
    """merge per-second histograms inside or outside the burst window"""
    st = fin["start_unix_nano"] / 1e9
    b0, b1 = st + fin["burst_at_sec"], st + fin["burst_at_sec"] + fin["burst_len_sec"]
    hs = []
    for sec, m in r["per_second_hist"].items():
        s = int(sec)
        inb = b0 <= s < b1
        # skip the first 3 s of publishing (warm-up) and the edges of the burst
        if s < st + 3 or (not burst and (b0 - 1 <= s < b1 + 2)):
            continue
        if inb == burst and cls in m:
            hs.append(m[cls])
    return merge(hs)


md = ["# RoomCast results", "",
      "One 2-vCPU VM. The edge is pinned to CPU 0 with GOMAXPROCS=1; the publisher and the viewer fleet share CPU 1. "
      "Latency is publish-to-client from the publisher's timestamp (same host clock), measured by the viewer fleet. "
      "Generated by `bench/plot.py` from `results/*.jsonl`.", ""]

# ---- memory
mem = [json.loads(l) for l in open(os.path.join(d, "memory.jsonl"))] if os.path.exists(os.path.join(d, "memory.jsonl")) else []
if mem:
    md += ["## 1. Memory per idle connection", "",
           "Viewers connect, join a room and stay idle (publisher sends nothing). Edge process numbers are deltas from the empty edge after a forced GC; "
           "host MemAvailable drop also counts kernel socket memory for both ends of every connection (client and server on this box).", "",
           "| transport | connections | goroutines | edge RSS per conn | Go heap per conn | goroutine stacks per conn | host memory per conn (both socket ends) |",
           "|---|---|---|---|---|---|---|"]
    for m in mem:
        a, b, n = m["after"], m["before"], m["conns"]
        md.append(f"| {m['transport']} | {n:,} | {a['goroutines']:,} | {(a['rss_bytes']-b['rss_bytes'])/n/1024:.1f} KiB | "
                  f"{(a['heap_inuse_bytes']-b['heap_inuse_bytes'])/n/1024:.1f} KiB | {(a['stack_inuse_bytes']-b['stack_inuse_bytes'])/n/1024:.1f} KiB | "
                  f"{m['mem_available_drop_kib']/n:.1f} KiB |")
    big = {m["transport"]: m for m in mem if m["conns"] == max(x["conns"] for x in mem)}
    if "std" in big and "epoll" in big:
        per = {t: (big[t]["after"]["rss_bytes"] - big[t]["before"]["rss_bytes"]) / big[t]["conns"] for t in big}
        stk = {t: (big[t]["after"]["stack_inuse_bytes"] - big[t]["before"]["stack_inuse_bytes"]) / big[t]["conns"] for t in big}
        gor = {t: big[t]["after"]["goroutines"] for t in big}
        np_note = ""
        if "netpoll" in per:
            rank = sorted(per, key=per.get)
            where = {0: "the least of the three", 1: "between the other two", 2: "the most of the three"}[rank.index("netpoll")]
            np_note = (f" CloudWeGo Netpoll uses {per['netpoll']/1024:.1f} KiB per idle connection ({where}), with {gor['netpoll']:,} goroutines "
                       f"and {stk['netpoll']/1024:.1f} KiB of goroutine stacks per connection.")
        kern = {t: big[t]["mem_available_drop_kib"] / big[t]["conns"] - (big[t]["after"]["rss_bytes"] - big[t]["before"]["rss_bytes"]) / big[t]["conns"] / 1024 for t in big}
        md += ["", f"At {big['epoll']['conns']:,} connections the event-loop edge uses {per['std']/per['epoll']:.1f}x less process memory per idle connection "
               f"({per['epoll']/1024:.1f} vs {per['std']/1024:.1f} KiB): the goroutine-per-connection build keeps two parked goroutines per connection "
               f"({gor['std']:,} goroutines, {stk['std']/1024:.1f} KiB of stacks per connection) and their per-connection state. Everything else in the host column (about "
               f"{min(kern.values()):.0f} to {max(kern.values()):.0f} KiB per connection) is the kernel's socket memory for both ends plus the viewer "
               "fleet's own state, which does not depend on the edge build. "
               "This VM's 20,000 file-descriptor limit per process capped the test at 18,000 connections." + np_note, ""]
    fig, ax = plt.subplots(figsize=(5.5, 3.4))
    for tr in ["std", "epoll", "netpoll"]:
        xs = [m["conns"] for m in mem if m["transport"] == tr]
        ys = [(m["after"]["rss_bytes"] - m["before"]["rss_bytes"]) / 2**20 for m in mem if m["transport"] == tr]
        ax.plot(xs, ys, "-o", color=COL[tr], label=tr)
    ax.set_xlabel("idle connections")
    ax.set_ylabel("edge RSS increase (MiB)")
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "memory.png"), dpi=150)

runs = [json.loads(l) for l in open(os.path.join(d, "runs.jsonl"))] if os.path.exists(os.path.join(d, "runs.jsonl")) else []


def final(label):
    p = os.path.join(d, f"final-{label}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def edge_delta(r, i=0):
    a, b = r["edge_stats_after"][i], r["edge_stats_before"][i]
    if not a or not b:
        return None
    return {k: a[k] - b[k] for k in ["cpu_sec", "delivered_frames", "delivered_bytes", "events_in"]} | {
        "dropped": {k: a["dropped"][k] - b["dropped"][k] for k in a["dropped"]}, "kicked": a["kicked"] - b["kicked"],
        "rss": a["rss_bytes"], "level_end": a["degrade_level"]}


fan = [r for r in runs if r["label"].startswith("fanout")]
if fan:
    hot = fan[0].get("verify", {}).get("auction_checked", 0)
    md += ["## 2. Fan-out latency, 1x and a 10x burst", "",
           f"{fan[0]['config']['Conns']:,} viewers: {hot:,} in the hot room (battle + auction), the rest over 499 tail rooms. Hot-room rates per second at 1x: "
           "comments 20, gifts 10, battle scores 4, auction bids 2, moderation 0.2; a 10x burst for 10 s. Base excludes 1 s around the burst. "
           "SLO used for 'within SLO': auction and battle 200 ms, gifts 500 ms, comments and moderation 1 s.", "",
           "| run | window | auction p50 / p99 ms | auction within 200 ms | battle p99 | gift p99 | comment p99 | moderation p99 | comments delivered | edge CPU s per M frames |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), sharey=True)
    for r in fan:
        fin = final(r["label"])
        if not fin:
            continue
        tr = "std" if "std" in r["label"] else "netpoll" if "netpoll" in r["label"] else "epoll"
        ed = edge_delta(r)
        cpm = ed["cpu_sec"] / (ed["delivered_frames"] / 1e6) if ed and ed["delivered_frames"] else float("nan")
        for burst in [False, True]:
            h = {c: window(r, fin, c, burst) for c in CLASSES}
            md.append(f"| {r['label']} | {'10x burst' if burst else '1x'} | {hq(h['auction'],.5):.1f} / {hq(h['auction'],.99):.1f} | "
                      f"{100*within(h['auction'],200):.2f}% | {hq(h['battle'],.99):.1f} | {hq(h['gift'],.99):.1f} | {hq(h['comment'],.99):.1f} | "
                      f"{hq(h['moderation'],.99):.1f} | {h['comment']['n']:,} | {cpm:.2f} |")
        if r["label"].endswith("-1") and tr in COL:
            st = fin["start_unix_nano"] / 1e9
            secs = sorted(int(s) for s in r["per_second_hist"])
            for ax, cls in zip(axes, ["auction", "comment"]):
                xs = [s - st for s in secs if cls in r["per_second_hist"][str(s)]]
                ys = [hq(r["per_second_hist"][str(s)][cls], .99) for s in secs if cls in r["per_second_hist"][str(s)]]
                ax.plot(xs, ys, color=COL[tr], label=tr)
                ax.set_title(f"{cls} p99 per second", fontsize=9)
                ax.axvspan(fin["burst_at_sec"], fin["burst_at_sec"] + fin["burst_len_sec"], color="#f4e3c1", zorder=0)
    for ax in axes:
        ax.set_yscale("log")
        ax.set_xlabel("seconds since publishing started (shaded: 10x burst)")
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("ms")
    axes[0].legend(frameon=False)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "burst_latency.png"), dpi=150)
    md.append("")
    md += ["Edge-side degradation during the runs (dropped comments are sampled away by the per-viewer rate cap; nothing else is dropped):", "",
           "| run | frames delivered | comments dropped | kicked | gaps / resyncs | auction wrong at end | battle wrong at end | moderation behind at end |",
           "|---|---|---|---|---|---|---|---|"]
    for r in fan:
        ed = edge_delta(r)
        v = r.get("verify") or {}
        md.append(f"| {r['label']} | {ed['delivered_frames']:,} | {ed['dropped']['comment']:,} | {ed['kicked']} | {r['modseq_gaps']} / {r['resyncs']} | "
                  f"{v.get('auction_wrong',0)} of {v.get('auction_checked',0)} | {v.get('battle_wrong',0)} of {v.get('battle_checked',0)} | "
                  f"{v.get('moderation_behind',0)} of {v.get('moderation_checked',0)} |")
    md.append("")

slow = [r for r in runs if r["label"].startswith("slow")]
if slow:
    md += ["## 3. Slow viewers", "",
           f"2% of viewers read at {slow[0]['config']['SlowBps']/1000:.0f} KB/s through a 4 KiB receive buffer. A viewer whose socket backs up gets only "
           "moderation, auction, battle and gift frames until it catches up (its comments are dropped), its queue keeps only the latest auction and "
           "battle values, and edge send buffers are kept at 16 KiB so the backlog stays where it can be coalesced. Everyone else should not notice.", "",
           "| run | normal viewers: auction p99 ms (1x) | slow viewers: auction/battle p50 / p99 ms | comments dropped | kicked |", "|---|---|---|---|---|"]
    for r in slow:
        fin = final(r["label"])
        ed = edge_delta(r)
        h = window(r, fin, "auction", False)
        md.append(f"| {r['label']} | {hq(h,.99):.1f} | {r.get('slow_clients_state_p50_ms', -1):.0f} / {r['slow_clients_state_p99_ms']:.0f} | {ed['dropped']['comment']:,} | {ed['kicked']} |")
    md.append("")

kill = [r for r in runs if r["label"].startswith("kill")]
if kill:
    md += [f"## 4. Killing an edge with {kill[0]['config']['Conns']//2:,} viewers", "",
           f"Two edges, {kill[0]['config']['Conns']//2:,} viewers each. Edge 1 gets SIGKILL 25 s in; its viewers reconnect to edge 2, which admits at most 5,000 new connections per second "
           "(burst 500) and answers the rest with a retry-after hint. naive: retry every 50 ms and ignore hints. jitter: honour the hint plus exponential backoff with jitter.", "",
           "| policy | lost | recovered | p50 s | p99 s | max s | retry responses | auction p99 ms in the 10 s after the kill | auction wrong at end | moderation behind at end |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in kill:
        pol = r["label"].split("-")[1]
        rec = r.get("recovery") or {}
        tk = float(open(os.path.join(d, f"kill-{pol}.time")).read()) if os.path.exists(os.path.join(d, f"kill-{pol}.time")) else None
        hs = [m["auction"] for s, m in r["per_second_hist"].items() if tk and tk <= int(s) < tk + 10 and "auction" in m]
        v = r.get("verify") or {}
        md.append(f"| {pol} | {rec.get('lost',0):.0f} | {rec.get('recovered',0):.0f} | {rec.get('p50_sec',float('nan')):.2f} | {rec.get('p99_sec',float('nan')):.2f} | "
                  f"{rec.get('max_sec',float('nan')):.2f} | {r['retry_responses']:,} | {hq(merge(hs),.99):.0f} | "
                  f"{v.get('auction_wrong',0)} of {v.get('auction_checked',0)} | {v.get('moderation_behind',0)} of {v.get('moderation_checked',0)} |")
    md.append("")

open(os.path.join(d, "SUMMARY.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
